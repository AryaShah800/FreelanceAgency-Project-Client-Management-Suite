-- PostgreSQL 16 baseline for a new, invite-only agency installation.
-- Test and review this migration against a disposable Neon branch before launch.
CREATE TABLE agencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    gstin VARCHAR(255),
    pan VARCHAR(255),
    registered_address TEXT,
    state_code VARCHAR(255),
    bank_name VARCHAR(255),
    bank_account_number VARCHAR(255),
    bank_ifsc VARCHAR(255),
    subscription_plan VARCHAR(255),
    gst_registered BOOLEAN NOT NULL DEFAULT TRUE,
    tax_state VARCHAR(255) DEFAULT 'Maharashtra',
    lut_details VARCHAR(255) DEFAULT '',
    legal_template TEXT,
    proposal_defaults_initialized BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER', 'CLIENT')),
    hourly_rate DOUBLE PRECISION,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP
);

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    company_name VARCHAR(255) NOT NULL,
    contact_person VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    gstin VARCHAR(255),
    pan VARCHAR(255),
    registered_address TEXT,
    state_code VARCHAR(255),
    deal_stage VARCHAR(32),
    created_at TIMESTAMP
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    budget NUMERIC(38,2) NOT NULL,
    deadline DATE,
    created_at TIMESTAMP
);

CREATE TABLE project_members (
    project_id BIGINT NOT NULL REFERENCES projects(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    PRIMARY KEY (project_id, user_id)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    assigned_to BIGINT REFERENCES app_users(id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    status VARCHAR(32) NOT NULL,
    estimated_hours DOUBLE PRECISION,
    actual_hours DOUBLE PRECISION,
    is_client_visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    invoice_number VARCHAR(255) NOT NULL UNIQUE,
    subtotal NUMERIC(38,2) NOT NULL,
    cgst NUMERIC(38,2) NOT NULL DEFAULT 0,
    sgst NUMERIC(38,2) NOT NULL DEFAULT 0,
    igst NUMERIC(38,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(38,2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    due_date DATE NOT NULL,
    is_recurring BOOLEAN,
    created_at TIMESTAMP
);

CREATE TABLE invoice_line_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    description VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(38,2) NOT NULL,
    amount NUMERIC(38,2) NOT NULL
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    amount NUMERIC(38,2) NOT NULL,
    razorpay_payment_id VARCHAR(255) UNIQUE,
    razorpay_order_id VARCHAR(255),
    paid_at TIMESTAMP
);

CREATE TABLE proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 0,
    share_token VARCHAR(255) NOT NULL UNIQUE,
    agency_id BIGINT REFERENCES agencies(id),
    client_name VARCHAR(255) NOT NULL,
    project_scope TEXT,
    deliverables TEXT,
    payment_terms TEXT,
    document_html TEXT,
    payment_milestones_json TEXT,
    estimated_budget NUMERIC(38,2),
    is_signed BOOLEAN NOT NULL DEFAULT FALSE,
    signature_name VARCHAR(255),
    signed_at TIMESTAMP,
    signature_hash VARCHAR(255),
    contract_pdf BYTEA,
    is_converted_to_project BOOLEAN NOT NULL DEFAULT FALSE,
    created_project_id BIGINT,
    deposit_invoice_number VARCHAR(255),
    deposit_amount NUMERIC(38,2),
    expires_at TIMESTAMP,
    is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP
);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    description VARCHAR(255) NOT NULL,
    amount NUMERIC(38,2) NOT NULL,
    category VARCHAR(255) NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE time_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP,
    duration_minutes INTEGER,
    is_billed BOOLEAN NOT NULL DEFAULT FALSE,
    invoice_id BIGINT REFERENCES invoices(id)
);

CREATE TABLE task_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    author_id BIGINT NOT NULL REFERENCES app_users(id),
    content TEXT NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    actor VARCHAR(255) NOT NULL,
    action VARCHAR(255) NOT NULL,
    details TEXT,
    timestamp TIMESTAMP
);

CREATE TABLE contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id BIGINT REFERENCES proposals(id),
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    client_id BIGINT NOT NULL REFERENCES clients(id),
    contract_number VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(32) NOT NULL,
    current_version_id BIGINT,
    stamping_reference VARCHAR(255),
    share_token VARCHAR(255) UNIQUE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE contract_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES contracts(id),
    version_number INTEGER NOT NULL,
    canonical_json TEXT,
    canonical_json_hash VARCHAR(64),
    pdf_binary BYTEA,
    pdf_sha256 VARCHAR(64),
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    project_summary TEXT,
    technical_stack TEXT,
    deliverables_json TEXT,
    client_dependencies TEXT,
    technical_exclusions TEXT,
    created_at TIMESTAMP,
    locked_at TIMESTAMP
);

CREATE TABLE contract_signers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_version_id BIGINT NOT NULL REFERENCES contract_versions(id),
    signer_role VARCHAR(32) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    designation VARCHAR(255),
    organization_name VARCHAR(255),
    signing_order INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP
);

CREATE TABLE contract_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES contracts(id),
    contract_version_id BIGINT REFERENCES contract_versions(id),
    sequence_number BIGINT NOT NULL,
    event_type VARCHAR(255) NOT NULL,
    actor_id VARCHAR(255) NOT NULL,
    payload_digest VARCHAR(64),
    prev_event_hash VARCHAR(64),
    event_hash VARCHAR(64) NOT NULL,
    timestamp TIMESTAMP NOT NULL
);

CREATE TABLE contract_amendments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_contract_id BIGINT NOT NULL REFERENCES contracts(id),
    new_version_id BIGINT NOT NULL REFERENCES contract_versions(id),
    change_request_number VARCHAR(255) NOT NULL UNIQUE,
    scope_delta TEXT,
    cost_delta NUMERIC(38,2),
    timeline_delta_days INTEGER,
    approved_by VARCHAR(255),
    created_at TIMESTAMP
);

CREATE TABLE signature_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_signer_id BIGINT NOT NULL REFERENCES contract_signers(id),
    contract_version_id BIGINT NOT NULL REFERENCES contract_versions(id),
    signed_at TIMESTAMP NOT NULL,
    ip_address VARCHAR(255) NOT NULL,
    user_agent TEXT,
    auth_method VARCHAR(32) NOT NULL,
    consent_statement TEXT NOT NULL,
    signature_type VARCHAR(32) NOT NULL,
    otp_token_digest VARCHAR(255)
);

CREATE TABLE account_action_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    purpose VARCHAR(32) NOT NULL CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE agency_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    invited_by_id BIGINT NOT NULL REFERENCES app_users(id),
    email VARCHAR(254) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'MEMBER')),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    accepted_at TIMESTAMP,
    revoked_at TIMESTAMP
);

CREATE TABLE platform_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    bootstrap_completed BOOLEAN NOT NULL DEFAULT FALSE
);
INSERT INTO platform_state (id, bootstrap_completed) VALUES (1, FALSE);

CREATE INDEX idx_users_agency_role ON app_users (agency_id, role);
CREATE INDEX idx_tasks_assignee ON tasks (assigned_to, project_id);
CREATE INDEX idx_tasks_project ON tasks (project_id);
CREATE INDEX idx_clients_agency ON clients (agency_id);
CREATE INDEX idx_projects_client ON projects (client_id);
CREATE INDEX idx_invoices_project ON invoices (project_id);
CREATE INDEX idx_proposals_agency_created ON proposals (agency_id, created_at);
CREATE INDEX idx_account_tokens_user_purpose ON account_action_tokens (user_id, purpose, used_at);
CREATE INDEX idx_invites_agency_email ON agency_invitations (agency_id, email, accepted_at, revoked_at);
